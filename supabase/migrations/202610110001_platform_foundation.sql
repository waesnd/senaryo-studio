-- Tüm araçlar aynı ortak UTC günlük bütçeyi ve deneme hız sınırını tüketir.
CREATE OR REPLACE FUNCTION public.reserve_ai_usage(p_request_id uuid,p_operation text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE uid uuid:=public.require_user(); used integer; attempted integer; legacy_used integer; minute_used integer; active_used integer; existing public.ai_usage_reservations; at_time timestamptz:=now(); reset_at timestamptz; next_expiry timestamptz;
BEGIN
 IF p_request_id IS NULL OR p_operation IS NULL OR p_operation NOT IN ('generate','scenes','beatsheet','dramaturg','karakterbible','puan','karakter','pitch','herosjourney','diyalog','logline') THEN RAISE EXCEPTION 'INVALID_OPERATION' USING ERRCODE='22023'; END IF;
 PERFORM pg_advisory_xact_lock(hashtextextended('ai:'||uid::text,0));
 SELECT * INTO existing FROM public.ai_usage_reservations WHERE request_id=p_request_id;
 IF FOUND THEN RETURN jsonb_build_object('allowed',false,'code','DUPLICATE_REQUEST','remaining',0,'retryAfterMs',0); END IF;
 UPDATE public.ai_usage_reservations SET status='expired',settled_at=at_time WHERE user_id=uid AND status='reserved' AND expires_at<=at_time;
 reset_at:=date_trunc('day',at_time AT TIME ZONE 'UTC') AT TIME ZONE 'UTC'+interval '1 day';
 SELECT count(*) INTO used FROM public.ai_usage_reservations WHERE user_id=uid AND created_at>=reset_at-interval '1 day' AND status IN ('reserved','succeeded');
 -- Eski günlük kayıtlar taşınana kadar bütçede hesaba katılır; migration ücret üretmez.
 legacy_used:=(SELECT count(*) FROM public.kullanim_log WHERE user_id=uid AND created_at>=reset_at-interval '1 day');
 used:=used+legacy_used;
 SELECT count(*)+legacy_used INTO attempted FROM public.ai_usage_reservations WHERE user_id=uid AND created_at>=reset_at-interval '1 day';
 SELECT count(*) INTO minute_used FROM public.ai_usage_reservations WHERE user_id=uid AND created_at>at_time-interval '1 minute';
 IF used>=50 THEN RETURN jsonb_build_object('allowed',false,'code','DAILY_LIMIT','remaining',0,'retryAfterMs',ceil(extract(epoch FROM reset_at-at_time)*1000),'resetAt',reset_at,'limit',50); END IF;
 IF attempted>=100 THEN RETURN jsonb_build_object('allowed',false,'code','DAILY_ATTEMPT_LIMIT','remaining',greatest(0,50-used),'retryAfterMs',ceil(extract(epoch FROM reset_at-at_time)*1000),'resetAt',reset_at,'limit',50,'attemptLimit',100); END IF;
 IF minute_used>=20 THEN RETURN jsonb_build_object('allowed',false,'code','RATE_LIMIT','remaining',50-used,'retryAfterMs',60000,'limit',50); END IF;
 SELECT count(*),min(expires_at) INTO active_used,next_expiry FROM public.ai_usage_reservations WHERE user_id=uid AND status='reserved';
 IF active_used>=3 THEN RETURN jsonb_build_object('allowed',false,'code','CONCURRENCY_LIMIT','remaining',50-used,'retryAfterMs',greatest(1000,ceil(extract(epoch FROM next_expiry-at_time)*1000)),'limit',50); END IF;
 INSERT INTO public.ai_usage_reservations(request_id,user_id,operation) VALUES(p_request_id,uid,p_operation) ON CONFLICT DO NOTHING;
 IF NOT FOUND THEN RETURN jsonb_build_object('allowed',false,'code','DUPLICATE_REQUEST','remaining',50-used,'retryAfterMs',0); END IF;
 RETURN jsonb_build_object('allowed',true,'code','RESERVED','remaining',49-used,'retryAfterMs',0,'resetAt',reset_at,'limit',50,'requestId',p_request_id);
END $$;
CREATE OR REPLACE FUNCTION public.settle_ai_usage(p_request_id uuid,p_success boolean)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE reservation public.ai_usage_reservations;
BEGIN
 IF coalesce(auth.role(),'')<>'service_role' THEN RAISE EXCEPTION 'SERVER_REQUIRED' USING ERRCODE='42501'; END IF;
 IF p_success IS NULL THEN RAISE EXCEPTION 'INVALID_SETTLEMENT'; END IF;
 SELECT * INTO reservation FROM public.ai_usage_reservations WHERE request_id=p_request_id;
 IF NOT FOUND THEN RAISE EXCEPTION 'RESERVATION_NOT_FOUND' USING ERRCODE='42501'; END IF;
 PERFORM pg_advisory_xact_lock(hashtextextended('ai:'||reservation.user_id::text,0));
 SELECT * INTO reservation FROM public.ai_usage_reservations WHERE request_id=p_request_id FOR UPDATE;
 IF reservation.status='reserved' THEN
  UPDATE public.ai_usage_reservations SET status=CASE WHEN p_success THEN 'succeeded' ELSE 'failed' END,settled_at=now() WHERE request_id=p_request_id RETURNING * INTO reservation;
 END IF;
 RETURN jsonb_build_object('ok',true,'status',reservation.status);
END $$;

