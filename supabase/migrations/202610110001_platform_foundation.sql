CREATE OR REPLACE FUNCTION public.list_conversations(p_before_at timestamptz DEFAULT NULL,p_before_id bigint DEFAULT NULL,p_limit integer DEFAULT 30)
RETURNS TABLE(peer_id uuid,last_id bigint,icerik text,created_at timestamptz,gonderen uuid,medya_asset_id uuid,ses_asset_id uuid,unread_count bigint)
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE uid uuid:=public.require_user();
BEGIN
 RETURN QUERY WITH inbox AS (
  SELECT CASE WHEN m.gonderen=uid THEN m.alan ELSE m.gonderen END AS peer,m.*
  FROM public.mesajlar m WHERE (m.gonderen=uid OR m.alan=uid) AND NOT public.is_blocked_pair(m.gonderen,m.alan)
 ), ranked AS (
  SELECT i.*,row_number() OVER(PARTITION BY i.peer ORDER BY i.created_at DESC,i.id DESC) AS position,
   count(*) FILTER(WHERE i.alan=uid AND NOT i.okundu) OVER(PARTITION BY i.peer) AS unread
  FROM inbox i
 )
 SELECT r.peer,r.id,r.icerik,r.created_at,r.gonderen,r.medya_asset_id,r.ses_asset_id,r.unread
 FROM ranked r WHERE r.position=1 AND (p_before_at IS NULL OR (r.created_at,r.id)<(p_before_at,coalesce(p_before_id,9223372036854775807)))
 ORDER BY r.created_at DESC,r.id DESC LIMIT least(greatest(coalesce(p_limit,30),1),100);
END $$;
