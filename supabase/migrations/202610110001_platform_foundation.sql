CREATE OR REPLACE FUNCTION public.legacy_scenario_document(p_row jsonb)
RETURNS jsonb LANGUAGE plpgsql IMMUTABLE SET search_path=public,pg_temp AS $$
DECLARE r jsonb:=p_row; parsed jsonb;
BEGIN
 IF r ? 'veri' AND jsonb_typeof(r->'veri')='string' THEN
  BEGIN parsed:=(r->>'veri')::jsonb; r:=r || coalesce(parsed->'senaryo',parsed); EXCEPTION WHEN OTHERS THEN NULL; END;
 END IF;
 IF jsonb_typeof(r->'document')='object' THEN RETURN r->'document'; END IF;
 RETURN jsonb_build_object('schemaVersion',1,'title',coalesce(nullif(r->>'baslik',''),'İsimsiz senaryo'),
  'tagline',coalesce(r->>'tagline',''),'synopsis',coalesce(r->>'ana_fikir',''),
  'characters',CASE WHEN coalesce(r->>'karakter','')='' THEN '[]'::jsonb ELSE
   jsonb_build_array(jsonb_build_object('id','legacy-character','name','Karakter','description',r->>'karakter')) END,
  'scenes',CASE WHEN coalesce(r->>'sahne',r->>'acilis_sahnesi','')='' THEN '[]'::jsonb ELSE
   jsonb_build_array(jsonb_build_object('id','legacy-scene','heading','AÇILIŞ SAHNESİ',
   'action',coalesce(r->>'sahne',r->>'acilis_sahnesi',''),'dialogue','[]'::jsonb)) END,
  'dramaticQuestion',coalesce(r->>'soru',r->>'buyuk_soru',''));
END $$;
UPDATE public.senaryolar SET document=public.legacy_scenario_document(to_jsonb(senaryolar)) WHERE document IS NULL;
UPDATE public.senaryolar SET revision=1 WHERE revision IS NULL;
UPDATE public.senaryolar SET schema_version=1 WHERE schema_version IS NULL;
UPDATE public.senaryolar SET moderation_hidden=false WHERE moderation_hidden IS NULL;
UPDATE public.senaryo_versiyonlar SET snapshot=public.legacy_scenario_document(to_jsonb(senaryo_versiyonlar)) WHERE snapshot IS NULL;
-- Eski bağımsız arşiv kayıtlarını kullanıcının özel eserlerine bağla; veri kolonu korunur.
DO $$
DECLARE v record; sid bigint;
BEGIN
 FOR v IN SELECT * FROM public.senaryo_versiyonlar WHERE senaryo_id IS NULL ORDER BY id LOOP
  INSERT INTO public.senaryolar(user_id,tip,tur,baslik,tagline,ana_fikir,karakter,sahne,soru,document,paylasim_acik)
  VALUES(v.user_id,v.tip,v.tur,v.snapshot->>'title',v.snapshot->>'tagline',v.snapshot->>'synopsis',v.karakter,v.sahne,v.snapshot->>'dramaticQuestion',v.snapshot,false)
  RETURNING id INTO sid;
  UPDATE public.senaryo_versiyonlar SET senaryo_id=sid WHERE id=v.id;
 END LOOP;
END $$;
WITH numbered AS (SELECT id,row_number() OVER(PARTITION BY senaryo_id ORDER BY created_at,id)::int AS n FROM public.senaryo_versiyonlar)
UPDATE public.senaryo_versiyonlar v SET versiyon=n.n FROM numbered n WHERE v.id=n.id AND v.versiyon IS NULL;
UPDATE public.senaryo_versiyonlar SET label='Sürüm ' || versiyon WHERE label IS NULL;
UPDATE public.begeniler b SET senaryo_id=g.senaryo_id FROM public.gonderiler g WHERE b.senaryo_id IS NULL AND b.gonderi_id=g.id;
UPDATE public.kaydedilenler b SET senaryo_id=g.senaryo_id FROM public.gonderiler g WHERE b.senaryo_id IS NULL AND b.gonderi_id=g.id;
UPDATE public.raporlar r SET senaryo_id=g.senaryo_id FROM public.gonderiler g WHERE r.senaryo_id IS NULL AND r.icerik_turu='gonderi' AND r.icerik_id=g.id;

-- Duplicate/ambiguous legacy state is rejected instead of silently deleting content.
DO $$
DECLARE t text; count_bad bigint;
BEGIN
 FOREACH t IN ARRAY ARRAY['begeniler','kaydedilenler','raporlar'] LOOP
  EXECUTE format('SELECT count(*) FROM public.%I WHERE senaryo_id IS NULL',t) INTO count_bad;
  IF count_bad>0 THEN RAISE EXCEPTION 'PRECHECK: % tablosunda % çözümlenmemiş senaryo ilişkisi var.',t,count_bad; END IF;
 END LOOP;
 IF EXISTS(SELECT 1 FROM public.begeniler GROUP BY user_id,senaryo_id HAVING count(*)>1)
 OR EXISTS(SELECT 1 FROM public.kaydedilenler GROUP BY user_id,senaryo_id HAVING count(*)>1)
 OR EXISTS(SELECT 1 FROM public.raporlar GROUP BY rapor_eden,senaryo_id HAVING count(*)>1)
 OR EXISTS(SELECT 1 FROM public.senaryo_versiyonlar GROUP BY senaryo_id,versiyon HAVING count(*)>1)
 OR EXISTS(SELECT 1 FROM public.profiles WHERE username IS NOT NULL GROUP BY lower(username) HAVING count(*)>1)
 THEN RAISE EXCEPTION 'PRECHECK: tekrar eden ilişkiler/sürüm numaraları/kullanıcı adları var; preflight.sql ve upgrade kılavuzunu kullanın.'; END IF;
 IF EXISTS(SELECT 1 FROM public.senaryo_versiyonlar v JOIN public.senaryolar s ON s.id=v.senaryo_id WHERE v.user_id IS DISTINCT FROM s.user_id)
 OR EXISTS(SELECT 1 FROM public.gonderiler g JOIN public.senaryolar s ON s.id=g.senaryo_id WHERE g.user_id IS DISTINCT FROM s.user_id)
 THEN RAISE EXCEPTION 'PRECHECK: eser ile bağlı gönderi/sürüm sahipliği uyuşmuyor; doğrulanmış sahip mapping gerekir.'; END IF;
 IF EXISTS(SELECT 1 FROM public.gonderiler g LEFT JOIN public.senaryolar s ON s.id=g.senaryo_id WHERE s.id IS NULL)
 THEN RAISE EXCEPTION 'PRECHECK: gönderinin kaynak eseri yok; explicit mapping gerekir.'; END IF;
END $$;

