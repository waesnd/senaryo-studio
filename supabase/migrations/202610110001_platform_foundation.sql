CREATE OR REPLACE FUNCTION public.validate_scenario_document(p jsonb)
RETURNS void LANGUAGE plpgsql IMMUTABLE SET search_path=public,pg_temp AS $$
DECLARE c jsonb; s jsonb; d jsonb;
BEGIN
 IF p IS NULL OR jsonb_typeof(p)<>'object' OR octet_length(p::text)>1000000 OR p->>'schemaVersion' IS DISTINCT FROM '1'
 OR jsonb_typeof(p->'title') IS DISTINCT FROM 'string' OR length(p->>'title')>240
 OR jsonb_typeof(p->'tagline') IS DISTINCT FROM 'string' OR length(p->>'tagline')>2000
 OR jsonb_typeof(p->'synopsis') IS DISTINCT FROM 'string' OR length(p->>'synopsis')>100000
 OR jsonb_typeof(p->'dramaticQuestion') IS DISTINCT FROM 'string' OR length(p->>'dramaticQuestion')>10000
 OR jsonb_typeof(p->'characters') IS DISTINCT FROM 'array' OR jsonb_typeof(p->'scenes') IS DISTINCT FROM 'array'
 THEN RAISE EXCEPTION 'INVALID_DOCUMENT' USING ERRCODE='22023'; END IF;
 IF jsonb_array_length(p->'characters')>100 OR jsonb_array_length(p->'scenes')>500 THEN RAISE EXCEPTION 'DOCUMENT_LIMIT' USING ERRCODE='22023'; END IF;
 FOR c IN SELECT value FROM jsonb_array_elements(p->'characters') LOOP
  IF jsonb_typeof(c->'id') IS DISTINCT FROM 'string' OR length(c->>'id') NOT BETWEEN 1 AND 100
  OR jsonb_typeof(c->'name') IS DISTINCT FROM 'string' OR length(c->>'name')>200
  OR jsonb_typeof(c->'description') IS DISTINCT FROM 'string' OR length(c->>'description')>20000
  THEN RAISE EXCEPTION 'INVALID_CHARACTER' USING ERRCODE='22023'; END IF;
 END LOOP;
 FOR s IN SELECT value FROM jsonb_array_elements(p->'scenes') LOOP
  IF jsonb_typeof(s->'id') IS DISTINCT FROM 'string' OR length(s->>'id') NOT BETWEEN 1 AND 100
  OR jsonb_typeof(s->'heading') IS DISTINCT FROM 'string' OR length(s->>'heading')>1000
  OR jsonb_typeof(s->'action') IS DISTINCT FROM 'string' OR length(s->>'action')>100000
  OR jsonb_typeof(s->'dialogue') IS DISTINCT FROM 'array' THEN RAISE EXCEPTION 'INVALID_SCENE' USING ERRCODE='22023'; END IF;
  IF jsonb_array_length(s->'dialogue')>1000 THEN RAISE EXCEPTION 'DIALOGUE_LIMIT' USING ERRCODE='22023'; END IF;
  FOR d IN SELECT value FROM jsonb_array_elements(s->'dialogue') LOOP
   IF jsonb_typeof(d->'id') IS DISTINCT FROM 'string' OR length(d->>'id') NOT BETWEEN 1 AND 100
   OR jsonb_typeof(d->'character') IS DISTINCT FROM 'string' OR length(d->>'character')>200
   OR jsonb_typeof(d->'text') IS DISTINCT FROM 'string' OR length(d->>'text')>20000
   THEN RAISE EXCEPTION 'INVALID_DIALOGUE' USING ERRCODE='22023'; END IF;
  END LOOP;
  IF EXISTS(SELECT 1 FROM jsonb_array_elements(s->'dialogue') x GROUP BY x->>'id' HAVING count(*)>1) THEN RAISE EXCEPTION 'DUPLICATE_DIALOGUE_ID' USING ERRCODE='22023'; END IF;
 END LOOP;
 IF EXISTS(SELECT 1 FROM jsonb_array_elements(p->'characters') x GROUP BY x->>'id' HAVING count(*)>1)
 OR EXISTS(SELECT 1 FROM jsonb_array_elements(p->'scenes') x GROUP BY x->>'id' HAVING count(*)>1)
 THEN RAISE EXCEPTION 'DUPLICATE_ELEMENT_ID' USING ERRCODE='22023'; END IF;
END $$;

CREATE OR REPLACE FUNCTION public.normalize_hashtag(p text)
RETURNS text LANGUAGE sql IMMUTABLE SET search_path=public,pg_temp AS $$
 SELECT lower(translate(normalize(p,NFKC),'Iİ','ıi'))
$$;

CREATE OR REPLACE FUNCTION public.scenario_sync_fields()
RETURNS trigger LANGUAGE plpgsql SET search_path=public,pg_temp AS $$
BEGIN
 IF TG_OP='UPDATE' AND (NEW.user_id<>OLD.user_id OR NEW.id<>OLD.id) THEN RAISE EXCEPTION 'IMMUTABLE_OWNER'; END IF;
 IF NEW.document IS NULL THEN NEW.document:=public.legacy_scenario_document(to_jsonb(NEW)); END IF;
 PERFORM public.validate_scenario_document(NEW.document);
 NEW.baslik:=coalesce(nullif(btrim(NEW.document->>'title'),''),'Başlıksız eser'); NEW.tagline:=NEW.document->>'tagline'; NEW.ana_fikir:=NEW.document->>'synopsis'; NEW.ozet:=NEW.ana_fikir; NEW.soru:=NEW.document->>'dramaticQuestion';
 SELECT coalesce(array_agg(DISTINCT public.normalize_hashtag(match[1])),'{}') INTO NEW.etiketler FROM regexp_matches(normalize(NEW.baslik||' '||NEW.tagline||' '||NEW.ana_fikir,NFKC),'#([[:alnum:]_]+)','g') match;
 SELECT coalesce(string_agg((c->>'name')||': '||(c->>'description'),E'\n\n'),'') INTO NEW.karakter FROM jsonb_array_elements(NEW.document->'characters') c;
 SELECT coalesce(string_agg((s->>'heading')||E'\n'||(s->>'action')||E'\n'||coalesce((SELECT string_agg((d->>'character')||E'\n'||(d->>'text'),E'\n') FROM jsonb_array_elements(s->'dialogue') d),''),E'\n\n'),'') INTO NEW.sahne FROM jsonb_array_elements(NEW.document->'scenes') s;
 NEW.schema_version:=1; NEW.updated_at:=now();
 RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS scenario_sync_fields ON public.senaryolar;
CREATE TRIGGER scenario_sync_fields BEFORE INSERT OR UPDATE OF document,user_id,id ON public.senaryolar FOR EACH ROW EXECUTE FUNCTION public.scenario_sync_fields();

CREATE OR REPLACE FUNCTION public.sync_scenario_publication()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE gid bigint; tag_name text;
BEGIN
 IF TG_OP='DELETE' THEN RETURN OLD; END IF;
 -- Hashtag link changes across publications use one transaction lock; counts stay exact.
 PERFORM pg_advisory_xact_lock(hashtextextended('publication-hashtags',0));
 IF NEW.paylasim_acik AND NOT NEW.moderation_hidden THEN
  INSERT INTO public.gonderiler(user_id,senaryo_id,baslik,tagline,ana_fikir,metin,tip,tur,paylasim_acik,begeni_sayisi,yorum_sayisi,goruntuleme_sayisi)
  VALUES(NEW.user_id,NEW.id,NEW.baslik,NEW.tagline,NEW.ana_fikir,NEW.ana_fikir,NEW.tip,NEW.tur,true,NEW.begeni_sayisi,NEW.yorum_sayisi,NEW.goruntuleme_sayisi)
  ON CONFLICT(senaryo_id) DO UPDATE SET baslik=EXCLUDED.baslik,tagline=EXCLUDED.tagline,ana_fikir=EXCLUDED.ana_fikir,metin=EXCLUDED.metin,tip=EXCLUDED.tip,tur=EXCLUDED.tur,paylasim_acik=true,begeni_sayisi=EXCLUDED.begeni_sayisi,yorum_sayisi=EXCLUDED.yorum_sayisi,goruntuleme_sayisi=EXCLUDED.goruntuleme_sayisi,updated_at=now()
  RETURNING id INTO gid;
  DELETE FROM public.gonderi_hashtagler WHERE gonderi_id=gid;
  FOR tag_name IN SELECT DISTINCT public.normalize_hashtag(match[1]) FROM regexp_matches(normalize(NEW.baslik||' '||coalesce(NEW.tagline,'')||' '||coalesce(NEW.ana_fikir,''),NFKC),'#([[:alnum:]_]+)','g') match ORDER BY 1 LOOP
   INSERT INTO public.hashtagler(tag) VALUES(tag_name) ON CONFLICT(tag) DO NOTHING;
   INSERT INTO public.gonderi_hashtagler(gonderi_id,hashtag_id) SELECT gid,id FROM public.hashtagler WHERE tag=tag_name ON CONFLICT DO NOTHING;
  END LOOP;
 ELSE
  -- URL id sabit kalır; taslağı public policy zaten engeller.
  UPDATE public.gonderiler SET paylasim_acik=false,updated_at=now() WHERE senaryo_id=NEW.id;
  DELETE FROM public.gonderi_hashtagler WHERE gonderi_id IN (SELECT id FROM public.gonderiler WHERE senaryo_id=NEW.id);
 END IF;
 RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS scenario_publication ON public.senaryolar;
CREATE TRIGGER scenario_publication AFTER INSERT OR UPDATE ON public.senaryolar FOR EACH ROW EXECUTE FUNCTION public.sync_scenario_publication();

CREATE OR REPLACE FUNCTION public.refresh_social_counts()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE sid bigint; target uuid; actor uuid; delta integer:=CASE WHEN TG_OP='DELETE' THEN -1 ELSE 1 END;
BEGIN
 IF TG_TABLE_NAME IN ('begeniler','yorumlar') THEN
  sid:=CASE WHEN TG_OP='DELETE' THEN OLD.senaryo_id ELSE NEW.senaryo_id END;
  IF TG_TABLE_NAME='begeniler' THEN
   UPDATE public.senaryolar SET begeni_sayisi=greatest(0,coalesce(begeni_sayisi,0)+delta) WHERE id=sid RETURNING user_id INTO target;
  ELSE
   UPDATE public.senaryolar SET yorum_sayisi=greatest(0,coalesce(yorum_sayisi,0)+delta) WHERE id=sid RETURNING user_id INTO target;
  END IF;
  IF TG_OP='INSERT' AND target<>NEW.user_id THEN
   INSERT INTO public.bildirimler(alici_id,gonderen_id,tip,senaryo_id,icerik) VALUES(target,NEW.user_id,CASE WHEN TG_TABLE_NAME='begeniler' THEN 'begeni' ELSE 'yorum' END,sid,CASE WHEN TG_TABLE_NAME='yorumlar' THEN left(to_jsonb(NEW)->>'metin',160) ELSE NULL END);
  END IF;
 ELSIF TG_TABLE_NAME='takipler' THEN
  target:=CASE WHEN TG_OP='DELETE' THEN OLD.takip_edilen ELSE NEW.takip_edilen END;
  actor:=CASE WHEN TG_OP='DELETE' THEN OLD.takip_eden ELSE NEW.takip_eden END;
  UPDATE public.profiles SET takipci_sayisi=greatest(0,coalesce(takipci_sayisi,0)+delta) WHERE id=target;
  UPDATE public.profiles SET takip_sayisi=greatest(0,coalesce(takip_sayisi,0)+delta) WHERE id=actor;
  IF TG_OP='INSERT' THEN INSERT INTO public.bildirimler(alici_id,gonderen_id,tip) VALUES(target,actor,'takip'); END IF;
 ELSIF TG_TABLE_NAME='senaryolar' THEN
  actor:=CASE WHEN TG_OP='DELETE' THEN OLD.user_id ELSE NEW.user_id END;
  UPDATE public.profiles SET senaryo_sayisi=greatest(0,coalesce(senaryo_sayisi,0)+delta) WHERE id=actor;
 ELSIF TG_TABLE_NAME='gonderi_hashtagler' THEN
  UPDATE public.hashtagler h SET kullanim_sayisi=greatest(0,coalesce(kullanim_sayisi,0)+delta) WHERE h.id=CASE WHEN TG_OP='DELETE' THEN OLD.hashtag_id ELSE NEW.hashtag_id END;
 ELSIF TG_TABLE_NAME='challenge_katilimlar' THEN
  UPDATE public.challengelar c SET katilimci_sayisi=greatest(0,coalesce(katilimci_sayisi,0)+delta) WHERE c.id=CASE WHEN TG_OP='DELETE' THEN OLD.challenge_id ELSE NEW.challenge_id END;
 END IF;
 RETURN CASE WHEN TG_OP='DELETE' THEN OLD ELSE NEW END;
END $$;
DO $$ DECLARE t text; BEGIN
 FOREACH t IN ARRAY ARRAY['begeniler','yorumlar','takipler','senaryolar','gonderi_hashtagler','challenge_katilimlar'] LOOP
  EXECUTE format('DROP TRIGGER IF EXISTS social_counts ON public.%I',t);
  EXECUTE format('CREATE TRIGGER social_counts AFTER INSERT OR DELETE ON public.%I FOR EACH ROW EXECUTE FUNCTION public.refresh_social_counts()',t);
 END LOOP;
END $$;

