-- Server-owned upload intent registration: the browser cannot forge asset ownership.
CREATE OR REPLACE FUNCTION public.register_media_upload(p_id uuid,p_owner_id uuid,p_public_id text,p_resource_type text,p_intent text,p_mime_type text,p_bytes bigint,p_delivery_type text,p_expires_at timestamptz)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE pending integer; hourly integer;
BEGIN
 IF coalesce(auth.role(),'')<>'service_role' THEN RAISE EXCEPTION 'SERVER_REQUIRED' USING ERRCODE='42501'; END IF;
 IF p_id IS NULL OR p_owner_id IS NULL OR p_public_id IS DISTINCT FROM ('senaryo-studio/'||p_owner_id::text||'/'||p_id::text)
 OR p_bytes IS NULL OR p_bytes NOT BETWEEN 1 AND 3145728 OR p_expires_at IS NULL OR p_expires_at<=now() OR p_expires_at>now()+interval '15 minutes'
 THEN RAISE EXCEPTION 'INVALID_UPLOAD_INTENT' USING ERRCODE='22023'; END IF;
 PERFORM pg_advisory_xact_lock(hashtextextended('media:'||p_owner_id::text,0));
 IF EXISTS(SELECT 1 FROM public.media_assets WHERE id=p_id) THEN RETURN jsonb_build_object('allowed',false,'code','DUPLICATE_MEDIA_REQUEST','retryAfterMs',0); END IF;
 SELECT count(*) INTO pending FROM public.media_assets WHERE owner_id=p_owner_id AND status='pending' AND expires_at>now();
 IF pending>=10 THEN RETURN jsonb_build_object('allowed',false,'code','MEDIA_PENDING_LIMIT','retryAfterMs',600000); END IF;
 SELECT count(*) INTO hourly FROM public.media_assets WHERE owner_id=p_owner_id AND created_at>now()-interval '1 hour';
 IF hourly>=30 THEN RETURN jsonb_build_object('allowed',false,'code','MEDIA_HOURLY_LIMIT','retryAfterMs',3600000); END IF;
 INSERT INTO public.media_assets(id,owner_id,public_id,resource_type,intent,mime_type,bytes,delivery_type,expires_at)
 VALUES(p_id,p_owner_id,p_public_id,p_resource_type,p_intent,p_mime_type,p_bytes,p_delivery_type,p_expires_at);
 RETURN jsonb_build_object('allowed',true,'code','RESERVED','retryAfterMs',0,'assetId',p_id);
END $$;

CREATE OR REPLACE FUNCTION public.save_scenario(p_id bigint,p_document jsonb,p_tip text,p_tur text,p_expected_revision integer DEFAULT NULL)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE uid uuid:=public.require_user(); s public.senaryolar;
BEGIN
 PERFORM public.validate_scenario_document(p_document);
 IF length(coalesce(p_tip,'')) NOT BETWEEN 1 AND 100 OR length(coalesce(p_tur,'')) NOT BETWEEN 1 AND 100 THEN RAISE EXCEPTION 'INVALID_METADATA' USING ERRCODE='22023'; END IF;
 IF p_id IS NULL THEN
  INSERT INTO public.senaryolar(user_id,document,tip,tur) VALUES(uid,p_document,p_tip,p_tur) RETURNING * INTO s;
 ELSE
  SELECT * INTO s FROM public.senaryolar WHERE id=p_id AND user_id=uid FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'SCENARIO_NOT_FOUND' USING ERRCODE='42501'; END IF;
  IF p_expected_revision IS NULL OR s.revision<>p_expected_revision THEN RAISE EXCEPTION 'REVISION_CONFLICT' USING ERRCODE='40001'; END IF;
  UPDATE public.senaryolar SET document=p_document,tip=p_tip,tur=p_tur,revision=revision+1 WHERE id=p_id RETURNING * INTO s;
 END IF;
 RETURN to_jsonb(s);
END $$;
